-- NOT APPLIED. Repeat while old ingest drains; run before compatibility views.
-- New IDs start at 10^12; old IDs must remain below that boundary.
USE ROLE MARKETING_ENGINEER;
USE WAREHOUSE MARKETING_WH;
ALTER SESSION SET QUERY_TAG='prism-migration-20261119-catchup';


EXECUTE IMMEDIATE $$
DECLARE
  violation NUMBER;
  rejected EXCEPTION (-20001, 'Source ID range violated; stop cutover');
BEGIN
  SELECT COUNT(*) INTO :violation FROM (SELECT INGESTION_ID FROM MCC_RAW.MARKETING_DEV.STG_SURVEY_RESPONSES WHERE INGESTION_ID IS NULL OR INGESTION_ID>=1000000000000);
  IF (violation > 0) THEN RAISE rejected; END IF;
END;
$$;


EXECUTE IMMEDIATE $$
DECLARE
  violation NUMBER;
  rejected EXCEPTION (-20001, 'Same ID has different response content; stop cutover');
BEGIN
  SELECT COUNT(*) INTO :violation FROM (SELECT s.INGESTION_ID FROM MCC_RAW.MARKETING_DEV.STG_SURVEY_RESPONSES s JOIN MCC_MARKETING.PRISM.STG_SURVEY_RESPONSES d ON s.INGESTION_ID=d.INGESTION_ID WHERE s.RAW_DATA IS DISTINCT FROM d.RAW_DATA OR s.INSERTED_AT IS DISTINCT FROM d.INSERTED_AT);
  IF (violation > 0) THEN RAISE rejected; END IF;
END;
$$;


INSERT INTO MCC_MARKETING.PRISM.STG_SURVEY_RESPONSES (INGESTION_ID, RAW_DATA, INSERTED_AT)
SELECT s.INGESTION_ID,s.RAW_DATA,s.INSERTED_AT FROM MCC_RAW.MARKETING_DEV.STG_SURVEY_RESPONSES s
WHERE NOT EXISTS (SELECT 1 FROM MCC_MARKETING.PRISM.STG_SURVEY_RESPONSES d WHERE d.INGESTION_ID=s.INGESTION_ID);

EXECUTE IMMEDIATE $$
DECLARE
  violation NUMBER;
  rejected EXCEPTION (-20001, 'Old ingestion still advancing; repeat reconciliation after drain');
BEGIN
  SELECT COUNT(*) INTO :violation FROM (SELECT s.INGESTION_ID FROM MCC_RAW.MARKETING_DEV.STG_SURVEY_RESPONSES s WHERE NOT EXISTS (SELECT 1 FROM MCC_MARKETING.PRISM.STG_SURVEY_RESPONSES d WHERE d.INGESTION_ID=s.INGESTION_ID));
  IF (violation > 0) THEN RAISE rejected; END IF;
END;
$$;
