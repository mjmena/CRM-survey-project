GRANT SELECT ON VIEW MCC_MARKETING.PRISM.V_SURVEY_RESPONSE_DEMOGRAPHICS TO ROLE MCC_MARKETING_AUDIENCE_BUILDER_SFULL;

SELECT * FROM MCC_MARKETING.PRISM.V_SURVEY_RESPONSE_DEMOGRAPHICS LIMIT 0;
