-- Run via a fail-fast client: any error requires ROLLBACK, never a later COMMIT.
USE ROLE MARKETING_ENGINEER;
USE WAREHOUSE MARKETING_WH;


EXECUTE IMMEDIATE $$
DECLARE
  violation NUMBER;
  rejected EXCEPTION (-20001, 'Rollback response ID collision; reconcile explicitly');
BEGIN
  SELECT COUNT(*) INTO :violation FROM (SELECT s.INGESTION_ID FROM MCC_RAW.MARKETING_DEV.STG_SURVEY_RESPONSES s JOIN MCC_MARKETING.PRISM.STG_SURVEY_RESPONSES d ON s.INGESTION_ID=d.INGESTION_ID WHERE s.RAW_DATA IS DISTINCT FROM d.RAW_DATA OR s.INSERTED_AT IS DISTINCT FROM d.INSERTED_AT);
  IF (violation > 0) THEN RAISE rejected; END IF;
END;
$$;


BEGIN TRANSACTION;

INSERT INTO MCC_RAW.MARKETING_DEV.STG_SURVEY_RESPONSES (INGESTION_ID, RAW_DATA, INSERTED_AT) SELECT d.INGESTION_ID,d.RAW_DATA,d.INSERTED_AT FROM MCC_MARKETING.PRISM.STG_SURVEY_RESPONSES d WHERE NOT EXISTS (SELECT 1 FROM MCC_RAW.MARKETING_DEV.STG_SURVEY_RESPONSES s WHERE s.INGESTION_ID=d.INGESTION_ID);

DELETE FROM MCC_RAW.MARKETING_DEV.DIM_SURVEY_OPTIONS;

INSERT INTO MCC_RAW.MARKETING_DEV.DIM_SURVEY_OPTIONS (OPTION_ID, POLL_ID, QUESTION_KEY, OPTION_VALUE, OPTION_SOURCE, OPTION_LABEL, OPTION_DESCRIPTION, IS_CATCH_ALL, SORT_ORDER, UPDATED_AT) SELECT OPTION_ID, POLL_ID, QUESTION_KEY, OPTION_VALUE, OPTION_SOURCE, OPTION_LABEL, OPTION_DESCRIPTION, IS_CATCH_ALL, SORT_ORDER, UPDATED_AT FROM MCC_MARKETING.PRISM.DIM_SURVEY_OPTIONS;

DELETE FROM MCC_RAW.MARKETING_DEV.DIM_SURVEY_QUESTIONS;

INSERT INTO MCC_RAW.MARKETING_DEV.DIM_SURVEY_QUESTIONS  SELECT * FROM MCC_MARKETING.PRISM.DIM_SURVEY_QUESTIONS;

DELETE FROM MCC_RAW.MARKETING_DEV.DIM_SURVEY_TAXONOMY;

INSERT INTO MCC_RAW.MARKETING_DEV.DIM_SURVEY_TAXONOMY  SELECT * FROM MCC_MARKETING.PRISM.DIM_SURVEY_TAXONOMY;

DELETE FROM MCC_RAW.MARKETING_DEV.DIM_RESPONDENT_IDENTITY;

INSERT INTO MCC_RAW.MARKETING_DEV.DIM_RESPONDENT_IDENTITY  SELECT * FROM MCC_MARKETING.PRISM.DIM_RESPONDENT_IDENTITY;

DELETE FROM MCC_RAW.MARKETING_DEV.DIM_RESPONDENT_DEMOGRAPHICS;

INSERT INTO MCC_RAW.MARKETING_DEV.DIM_RESPONDENT_DEMOGRAPHICS  SELECT * FROM MCC_MARKETING.PRISM.DIM_RESPONDENT_DEMOGRAPHICS;

COMMIT;

